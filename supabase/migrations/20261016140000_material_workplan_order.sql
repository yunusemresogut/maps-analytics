-- Malzeme ve iş planı satırları eklendikleri sırada listelenir.
-- imported_at tek başına yetmez: Excel'den aktarılan tüm satırlar aynı
-- zaman damgasını alır ve veritabanı aralarındaki sırayı garanti etmez.
-- seq her insert'te (toplu insert'te satır sırasıyla) artan bir sayıdır.

ALTER TABLE public.store_materials ADD COLUMN IF NOT EXISTS seq bigint;
ALTER TABLE public.store_work_plan ADD COLUMN IF NOT EXISTS seq bigint;

-- Mevcut satırlar: eklenme zamanı, eşitlikte fiziksel kayıt sırası
WITH ordered AS (
	SELECT ctid, row_number() OVER (ORDER BY imported_at, ctid) AS rn
	FROM public.store_materials
)
UPDATE public.store_materials m SET seq = ordered.rn
FROM ordered WHERE m.ctid = ordered.ctid AND m.seq IS NULL;

WITH ordered AS (
	SELECT ctid, row_number() OVER (ORDER BY imported_at, ctid) AS rn
	FROM public.store_work_plan
)
UPDATE public.store_work_plan w SET seq = ordered.rn
FROM ordered WHERE w.ctid = ordered.ctid AND w.seq IS NULL;

ALTER TABLE public.store_materials ALTER COLUMN seq SET NOT NULL;
ALTER TABLE public.store_work_plan ALTER COLUMN seq SET NOT NULL;

ALTER TABLE public.store_materials ALTER COLUMN seq ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE public.store_work_plan ALTER COLUMN seq ADD GENERATED BY DEFAULT AS IDENTITY;

-- Yeni satırlar mevcutların ardından gelsin
SELECT setval(
	pg_get_serial_sequence('public.store_materials', 'seq'),
	COALESCE((SELECT MAX(seq) FROM public.store_materials), 0) + 1,
	false
);
SELECT setval(
	pg_get_serial_sequence('public.store_work_plan', 'seq'),
	COALESCE((SELECT MAX(seq) FROM public.store_work_plan), 0) + 1,
	false
);

CREATE INDEX IF NOT EXISTS store_materials_store_seq_idx ON public.store_materials (store_id, seq);
CREATE INDEX IF NOT EXISTS store_work_plan_store_seq_idx ON public.store_work_plan (store_id, seq);

